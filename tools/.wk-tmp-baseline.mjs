import { webkit } from 'playwright';
const b = await webkit.launch();
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 }, serviceWorkers: 'block' });
await ctx.route('**/*', r => (/klaviyo\.com/.test(r.request().url()) && r.request().method() !== 'GET') ? r.abort() : r.continue());
const page = await ctx.newPage();
const errs = [], http = [];
page.on('console', m => m.type() === 'error' && errs.push(m.text().slice(0, 250) + ' @ ' + (m.location()?.url || '').slice(0, 100)));
page.on('pageerror', e => errs.push('PAGEERROR ' + e.message.slice(0, 250)));
page.on('response', r => r.status() >= 400 && http.push(r.status() + ' ' + r.request().method() + ' ' + r.url().slice(0, 150)));
await page.goto('https://microvitamin.com/products/microvitamin', { waitUntil: 'load' });
await page.waitForTimeout(12000);
const c = {}; for (const e of errs) c[e] = (c[e] || 0) + 1;
console.log(JSON.stringify({ errs: c, http }, null, 1));
await b.close();
