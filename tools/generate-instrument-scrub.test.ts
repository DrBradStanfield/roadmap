// The stand-in catalogue allows only the reads scrub-vocabulary.ts makes today.
// A vocabulary that reads it any other way fails generation, by name.
describe('US-09 AC7j: the stand-in catalogue fails closed', () => {
  const real = readFileSync(join(ROOT, 'packages/health-core/src/scrub-vocabulary.ts'), 'utf8');
  const edit = (from: string, to: string) => {
    expect(real, `scrub-vocabulary.ts no longer holds ${from}: update this pin`).toContain(from);
    return real.replace(from, to);
  };
  const LABEL_READ = '...LAB_CATALOG.flatMap((entry) => [entry.key';
  it.each([
    ['metricNameWords(2)', edit('...metricNameWords(3),', '...metricNameWords(2),'), /metricNameWords\(2\)/],
    ['metricNameWords(3) twice', edit('...metricNameWords(3),', '...metricNameWords(3), ...metricNameWords(3),'), /metricNameWords\(3\)/],
    ['LAB_CATALOG read once more', edit(LABEL_READ, `...LAB_CATALOG.flatMap((entry) => entry.aliases), ${LABEL_READ}`), /LAB_CATALOG\[flatMap\] \(once more\)/],
    ['LAB_CATALOG read another way', edit(LABEL_READ, `...LAB_CATALOG.map((entry) => entry.key), ${LABEL_READ}`), /LAB_CATALOG\[map\]/],
    ['CATALOG_UNITS spread twice', edit('  ...CATALOG_UNITS,', '  ...CATALOG_UNITS,\n  ...CATALOG_UNITS,'), /CATALOG_UNITS\[Symbol\(Symbol\.iterator\)\] \(once more\)/],
    ['Object.values(LAB_CATALOG)', edit(LABEL_READ, `...Object.values(LAB_CATALOG), ${LABEL_READ}`), /LAB_CATALOG \(ownKeys\)/],
    ['"in" on LAB_CATALOG', edit(LABEL_READ, `...('flatMap' in LAB_CATALOG ? [] : []), ${LABEL_READ}`), /LAB_CATALOG \(has\)/],
  ])('%s makes generation fail', async (_label, vocabularySource, message) => {
    await expect(generate({ vocabularySource })).rejects.toThrow(message);
  });
});

describe('US-09 AC7j: TEST_ONLY_VOCABULARY stays test-only', () => {
  it('no tracked non-test source names it but the generated file and its generator', () => {
    const tracked = execFileSync('git', ['ls-files', '-z'], { cwd: ROOT, maxBuffer: 1 << 26 }).toString().split('\0');
    const users = tracked
      .filter((f) => /\.(ts|tsx|js|mjs|cjs|jsx|swift)$/.test(f) && !/\.test\.|(^|\/)tests?\//.test(f) && existsSync(join(ROOT, f)))
      .filter((f) => readFileSync(join(ROOT, f), 'utf8').includes('TEST_ONLY_VOCABULARY'));
    expect(users.sort()).toEqual(['instrument-scrub.mjs', 'tools/generate-instrument-scrub.mjs']);
  });
});

// The five helpers the server copy wrote in its own form. The generated file
// takes them from sentry-scrub-server.ts (the server's form); each case shows
// health-core's sentry-scrub.ts form gives the same output.
describe('US-09 AC7j: the five helpers match sentry-scrub.ts', () => {
  const TRACE_ID = 'e2123456789abcdef0123456789abcde';
  const SPAN_ID = 'e212345678abcdef';
  const textEvent = () => ({
    message: 'LDL 3.2 mmol/L', logentry: { message: 'weight 80 kg' },
    exception: { values: [{ value: 'a@b.co sent HbA1c 42' }, { value: 7 }] },
    extra: { note: 'e2 45' }, tags: { step: 'TSH 2.1' },
    contexts: {
      trace: { trace_id: TRACE_ID, span_id: SPAN_ID, parent_span_id: 'e2 45', links: [{ trace_id: TRACE_ID, span_id: 'e2 45' }, 'x'] },
      other: { trace_id: TRACE_ID },
    },
    breadcrumbs: [{ message: 'ldl 3.2' }, { data: { a: 'b12 300' } }],
    request: { url: '/v/ldl 3.2', query_string: 'q=ldl 3.2' },
  });

  it('isSensitiveKey: exact keys, substrings and case, through scrubSensitiveData', () => {
    const keys = { Weight: 1, WEIGHT_KG: 2, refreshToken: 3, statinDrug: 4, name: 5, page: 6, x_COOKIE_y: 7 };
    expect(generated.scrubSensitiveData(keys)).toEqual(browser.scrubSensitiveData(keys));
  });

  it('scrubSensitiveData: nesting, arrays, depth cap and primitives', () => {
    let deep: Record<string, unknown> = { leaf: 'x' };
    for (let i = 0; i < 12; i++) deep = { next: deep };
    for (const input of [null, undefined, 3, 'ldl', [{ ldl: 1 }, [{ note: 'n' }]], { a: { hdl: 1, b: [1, { value: 2 }] } }, deep]) {
      expect(generated.scrubSensitiveData(input)).toEqual(browser.scrubSensitiveData(input));
    }
  });

  it('keepIds: ids in their shape come back, anything else stays scrubbed', () => {
    const a = textEvent(), b = textEvent();
    generated.scrubEventText(a);
    browser.scrubEventText(b);
    expect(a.contexts).toEqual(b.contexts);
    expect(a.contexts.trace.trace_id).toBe(TRACE_ID);
  });

  it('scrubContexts: odd shapes (a string, an array, a null trace, links not an array)', () => {
    for (const contexts of ['ldl 3.2', ['ldl 3.2'], { trace: null }, { trace: { links: 'e2 45', trace_id: 5 } }, { trace: 'e2 45' }]) {
      const a = { contexts }, b = { contexts };
      generated.scrubEventText(a);
      browser.scrubEventText(b);
      expect(a).toEqual(b);
    }
  });

  it('scrubEventText: every free-text field', () => {
    const a = textEvent(), b = textEvent();
    generated.scrubEventText(a);
    browser.scrubEventText(b);
    expect(a).toEqual(b);
    expect(a.message).toBe('LDL [value]');
  });
});
