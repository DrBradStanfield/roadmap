// US-09 AC7j: instrument-scrub.mjs is generated from health-core's scrub, loads
// with nothing installed, carries none of the catalogue's graph, and fails CI
// when the source moves without a regeneration.
import { copyFileSync, mkdtempSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import * as vocabulary from '../packages/health-core/src/scrub-vocabulary';
import * as browser from '../packages/health-core/src/sentry-scrub';
// @ts-expect-error -- plain .mjs tool with no declarations.
import { BANNER, COMMAND, OUT, ROOT, generate } from './generate-instrument-scrub.mjs';
// @ts-expect-error -- generated plain .mjs with no declarations.
import * as generated from '../instrument-scrub.mjs';

type Generated = { code: string; inputs: string[]; vocabulary: { catalogInputs: string[] } };
let first: Generated;
let second: Generated;
const committed = readFileSync(OUT, 'utf8');

beforeAll(async () => {
  first = await generate();
  second = await generate();
});

describe('US-09 AC7j: the generated server scrub', () => {
  it(`is fresh: the committed file is what the generator writes (else run \`${COMMAND}\`)`, () => {
    expect(committed === first.code, `instrument-scrub.mjs is stale. Run: ${COMMAND}`).toBe(true);
  });

  it('is deterministic: two runs give the same bytes, with no absolute path', () => {
    expect(second.code === first.code).toBe(true);
    for (const leak of [ROOT, tmpdir(), '/Users/', '/home/', 'node_modules', 'Library/Caches']) {
      expect(first.code.includes(leak), `output holds ${leak}`).toBe(false);
    }
  });

  it('opens with the GENERATED marker naming the exact command', () => {
    expect(committed.split('\n')[0]).toBe(`// GENERATED by ${COMMAND} from packages/health-core/src (esbuild ${
      (BANNER as string).match(/esbuild ([\d.]+)/)![1]}). Do not edit.`);
    expect(committed.startsWith(BANNER)).toBe(true);
  });

  it("metafile: its inputs are the scrub files only, none of lab-catalog's import graph", () => {
    expect(first.vocabulary.catalogInputs).toContain('packages/health-core/src/lab-catalog.ts');
    expect(first.inputs.filter((f) => first.vocabulary.catalogInputs.includes(f))).toEqual([]);
    expect([...first.inputs].sort()).toEqual([
      'packages/health-core/src/instrument-scrub-entry.js',
      'packages/health-core/src/scrub-vocabulary.ts',
      'packages/health-core/src/sentry-scrub-server.ts',
      'packages/health-core/src/sentry-scrub.ts',
      'scrub-literals:lab-catalog',
    ]);
  });

  it('has no require(, no dynamic import( and no process.binding', () => {
    expect(committed).not.toMatch(/\brequire\s*\(|\bimport\s*\(|process\.binding/);
  });

  it('does nothing at load but define its lists, regexes and functions', () => {
    // Every top-level statement is a declaration or the export list; nothing
    // reads the process, the environment, the console, a timer or the network.
    const topLevel = committed.split('\n').filter((line) => /^\S/.test(line) && !/^(\/\/|var |function |export \{|\}|\]|\))/.test(line));
    expect(topLevel).toEqual([]);
    // (The words "console" and "fetch" appear only as breadcrumb category strings.)
    expect(committed).not.toMatch(/\b(process|globalThis|console|setTimeout|setInterval|setImmediate|queueMicrotask|fetch)\s*[.([]|import\.meta/);
  });
});

describe('US-09 AC7j: it loads with nothing installed', () => {
  let dir: string;
  beforeAll(() => { dir = mkdtempSync(join(tmpdir(), 'instrument-scrub-alone-')); });
  afterAll(() => rmSync(dir, { recursive: true, force: true }));

  it('copied alone into an empty folder, it imports by absolute path and scrubs', async () => {
    const lone = join(dir, 'instrument-scrub.mjs');
    copyFileSync(OUT, lone);
    const mod = await import(pathToFileURL(lone).href);
    const out = mod.scrubServerEvent({
      exception: { values: [{ type: 'Error', value: 'LDL 3.2 mmol/L for a@b.co' }] },
      extra: { weight: 80, step: 'save' },
      request: { url: 'https://shop.test/a?b=c', data: 'body', headers: { cookie: 'c', host: 'shop.test' } },
    });
    expect(out).toEqual({
      exception: { values: [{ type: 'Error', value: 'LDL [value] for [email]' }] },
      extra: { weight: '[Filtered]', step: 'save' },
      request: { url: 'https://shop.test/a', headers: { host: 'shop.test' } },
    });
  });
});

describe('US-09 AC7j: the swapped-in literal lists equal the real vocabulary', () => {
  // A catalogue change without a regeneration fails here, by list name.
  it.each(['SCRUB_UNITS', 'SCRUB_METRIC_WORDS', 'SCRUB_UNIT_PATTERN'] as const)('%s', (name) => {
    expect(generated[name], `${name} moved in the catalogue: run ${COMMAND}`).toEqual(vocabulary[name]);
  });
  it('SENSITIVE_EXACT_KEYS', () => {
    expect([...generated.SENSITIVE_EXACT_KEYS]).toEqual([...vocabulary.SENSITIVE_EXACT_KEYS]);
  });
});

// The five helpers the server copy wrote in its own form. The generated file
// takes them from sentry-scrub-server.ts (the server's form); each case shows
// health-core's sentry-scrub.ts form gives the same output.
describe('US-09 AC7j: the five helpers match sentry-scrub.ts', () => {
  const TRACE_ID = 'e2123456789abcdef0123456789abcde';
  const SPAN_ID = 'e212345678abcdef';
  const textEvent = () => ({
    message: 'LDL 3.2 mmol/L', logentry: { message: 'weight 80 kg' },
    exception: { values: [{ value: 'a@b.co sent HbA1c 42' }, { value: 7 }] },
    extra: { note: 'e2 45' }, tags: { step: 'TSH 2.1' },
    contexts: {
      trace: { trace_id: TRACE_ID, span_id: SPAN_ID, parent_span_id: 'e2 45', links: [{ trace_id: TRACE_ID, span_id: 'e2 45' }, 'x'] },
      other: { trace_id: TRACE_ID },
    },
    breadcrumbs: [{ message: 'ldl 3.2' }, { data: { a: 'b12 300' } }],
    request: { url: '/v/ldl 3.2', query_string: 'q=ldl 3.2' },
  });

  it('isSensitiveKey: exact keys, substrings and case, through scrubSensitiveData', () => {
    const keys = { Weight: 1, WEIGHT_KG: 2, refreshToken: 3, statinDrug: 4, name: 5, page: 6, x_COOKIE_y: 7 };
    expect(generated.scrubSensitiveData(keys)).toEqual(browser.scrubSensitiveData(keys));
  });

  it('scrubSensitiveData: nesting, arrays, depth cap and primitives', () => {
    let deep: Record<string, unknown> = { leaf: 'x' };
    for (let i = 0; i < 12; i++) deep = { next: deep };
    for (const input of [null, undefined, 3, 'ldl', [{ ldl: 1 }, [{ note: 'n' }]], { a: { hdl: 1, b: [1, { value: 2 }] } }, deep]) {
      expect(generated.scrubSensitiveData(input)).toEqual(browser.scrubSensitiveData(input));
    }
  });

  it('keepIds: ids in their shape come back, anything else stays scrubbed', () => {
    const a = textEvent(), b = textEvent();
    generated.scrubEventText(a);
    browser.scrubEventText(b);
    expect(a.contexts).toEqual(b.contexts);
    expect(a.contexts.trace.trace_id).toBe(TRACE_ID);
  });

  it('scrubContexts: odd shapes (a string, an array, a null trace, links not an array)', () => {
    for (const contexts of ['ldl 3.2', ['ldl 3.2'], { trace: null }, { trace: { links: 'e2 45', trace_id: 5 } }, { trace: 'e2 45' }]) {
      const a = { contexts }, b = { contexts };
      generated.scrubEventText(a);
      browser.scrubEventText(b);
      expect(a).toEqual(b);
    }
  });

  it('scrubEventText: every free-text field', () => {
    const a = textEvent(), b = textEvent();
    generated.scrubEventText(a);
    browser.scrubEventText(b);
    expect(a).toEqual(b);
    expect(a.message).toBe('LDL [value]');
  });
});
