#!/usr/bin/env node
/**
 * Guard: docs/products.md is the MASTER copy and must be a REAL committed file.
 *
 * Why this exists (direction INVERTED 2026-08-10, Brad's call)
 * -----------------------------------------------------------
 * Until 2026-08-10 the master lived in claude_business (Dropbox) and this repo
 * held a symlink — which made every Fly deploy do a dereference/restore dance
 * and made headless (CI) deploys impossible: the Docker build baked in whatever
 * the symlink resolved to, i.e. nothing on any machine but Brad's Mac.
 *
 * Now the MASTER lives HERE as a real tracked file, and claude_business holds
 * the symlink pointing back at this repo. If a commit ever records
 * docs/products.md as a symlink again (mode 120000), the repo — and therefore
 * every Fly image and CI deploy — loses the product knowledge content, and the
 * chatbot silently degrades with no error anywhere.
 *
 * Two more files share the rule (2026-10-14, claude_business
 * docs/chatbot-answer-bank-plan.md): docs/writing-style.md (kept identical
 * with the claude_business copy by its tools/sync-shared-docs.mjs) and
 * docs/chatbot/answer-bank.md (generated by that tool from the private answer
 * bank). The chatbot loads both at runtime. CI cannot see the private repo, so
 * it checks each against the sha256 the last sync recorded in its state file:
 * a hand edit here, or on GitHub, fails. Fix by editing the claude_business
 * master and rerunning `node tools/sync-shared-docs.mjs` there.
 *
 * This checks the git INDEX, because the index is what a commit records.
 *
 * Usage:  node scripts/check-symlinks.mjs        (exit 1 on violation)
 * Wired into: .git/hooks/pre-commit, `npm run check:symlinks` (npm test) and
 * the deploy workflow's guard step.
 */
import { execSync } from 'node:child_process'
import { createHash } from 'node:crypto'

/** Paths that must always be committed as REAL files (git mode 100644). */
const MUST_BE_REAL_FILE = ['docs/products.md', 'docs/writing-style.md', 'docs/chatbot/answer-bank.md']

/** Synced files: each must be committed, and match the sha256 its state file recorded. */
const SYNCED = {
  'docs/writing-style.md': 'docs/writing-style.sync.json',
  'docs/chatbot/answer-bank.md': 'docs/chatbot/answer-bank.sync.json',
}

/** The staged blob of a path, or null when the index has none. */
function staged(path) {
  try {
    return execSync(`git show ":${path}"`, { stdio: ['ignore', 'pipe', 'ignore'], maxBuffer: 64 * 1024 * 1024 })
  } catch {
    return null
  }
}

const GIT_MODE_SYMLINK = '120000'
let failed = false

for (const path of MUST_BE_REAL_FILE) {
  let entry
  try {
    entry = execSync(`git ls-files -s -- "${path}"`, { encoding: 'utf-8' }).trim()
  } catch {
    continue // not tracked in this checkout — nothing to guard
  }
  if (!entry) continue

  const mode = entry.split(/\s+/)[0]
  if (mode === GIT_MODE_SYMLINK) {
    failed = true
    console.error(`\n✖ ${path} is staged as a SYMLINK (mode ${mode}), not a real file.`)
    if (path !== 'docs/products.md') {
      console.error(`  A symlink is dangling in every Fly image and CI deploy, so the chatbot`)
      console.error(`  silently loses this file. Commit the real copy that`)
      console.error(`  claude_business tools/sync-shared-docs.mjs keeps in step.\n`)
      continue
    }
    console.error(`  This repo holds the MASTER copy (since 2026-08-10); committing a symlink`)
    console.error(`  strips the content out of every Fly image and CI deploy — the chatbot`)
    console.error(`  silently loses its product knowledge.`)
    console.error(`\n  If you meant to edit product content, edit the real file here directly.`)
    console.error(`  (claude_business/docs/products.md is now the symlink, pointing HERE.)\n`)
  }
}

for (const [path, statePath] of Object.entries(SYNCED)) {
  const blob = staged(path)
  const stateBlob = staged(statePath)
  let recorded = null
  try {
    recorded = stateBlob && JSON.parse(stateBlob.toString('utf-8')).sha256
  } catch {
    // unreadable state: reported below
  }
  const actual = blob && createHash('sha256').update(blob).digest('hex')
  if (!blob || !recorded || actual !== recorded) {
    failed = true
    console.error(`\n✖ ${path} ${!blob ? 'is not in the index (commit it)' : !recorded ? `has no readable hash in ${statePath}` : `does not match the hash in ${statePath}`}.`)
    console.error(`  It comes from claude_business (tools/sync-shared-docs.mjs); never edit it here.`)
    console.error(`  Edit the claude_business master and rerun \`node tools/sync-shared-docs.mjs\` there,`)
    console.error(`  then commit ${path} and ${statePath} together.\n`)
  }
}

if (failed) {
  console.error('Commit blocked by scripts/check-symlinks.mjs\n')
  process.exit(1)
}
